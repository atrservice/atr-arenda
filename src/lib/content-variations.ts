// 🔹 Функция выбора случайного элемента
export function getRandom<T>(array: T[]): T {
  return array[Math.floor(Math.random() * array.length)];
}

// 🔹 Функция выбора N уникальных элементов
export function getRandomMany<T>(array: T[], count: number): T[] {
  const shuffled = [...array].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// 🔹 Детерминированный выбор (по seed — для одинакового контента на одной странице)
export function getDeterministic<T>(array: T[], seed: string): T {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = ((hash << 5) - hash) + seed.charCodeAt(i);
    hash |= 0;
  }
  return array[Math.abs(hash) % array.length];
}